def _sort_key(x: QuotientElement) -> tuple[int, tuple[int, int, int, int]]:
    """The canonical order: lexicographic on (e, a, b, c, d)."""
    return (x.e, x.u)


def _closure(identity: QuotientElement, gens: Sequence[QuotientElement]) -> frozenset[QuotientElement]:
    """The subgroup generated by gens, by breadth first search from the identity.

    In a finite group the monoid generated by gens is already a group.
    """
    seen = {identity}
    queue = [identity]
    while queue:
        x = queue.pop()
        for g in gens:
            y = x * g
            if y not in seen:
                seen.add(y)
                queue.append(y)
    return frozenset(seen)


def _canonical_generators(
    identity: QuotientElement, elements: Iterable[QuotientElement]
) -> tuple[QuotientElement, ...]:
    """Scan in canonical order, keep what is not yet generated (def:canonical-generators)."""
    kept: list[QuotientElement] = []
    span = frozenset({identity})
    for x in sorted(elements, key=_sort_key):
        if x not in span:
            kept.append(x)
            span = _closure(identity, kept)
    return tuple(kept)


class QuotientSubgroup(api.QuotientSubgroup):
    """Toy implementation of :class:`arithkit_api.modular.subgroup.QuotientSubgroup`."""

    def __init__(
        self,
        parent: _QuotientGroup,
        gens: Sequence[QuotientElement],
        elements: frozenset[QuotientElement] | None = None,
    ) -> None:
        """The subgroup generated by gens; ``elements``, if given, must be that subgroup."""
        self._parent = parent
        identity = parent.identity()
        self._elements = _closure(identity, gens) if elements is None else elements
        self._gens = _canonical_generators(identity, self._elements)

    def parent(self) -> api_quotient.GL2ASubQuotient | api_quotient.GL2QSubQuotient:
        p = self._parent
        assert isinstance(p, GL2ASubQuotient | GL2QSubQuotient)
        return p

    def order(self) -> int:
        return len(self._elements)

    def index(self) -> int:
        return self._parent.order() // self.order()

    def elements(self) -> tuple[api_quotient.QuotientElement, ...]:
        return tuple(sorted(self._elements, key=_sort_key))

    def gens(self) -> tuple[api_quotient.QuotientElement, ...]:
        return self._gens

    def al_image(self) -> tuple[int, ...]:
        return tuple(sorted({x.e for x in self._elements}))

    def is_subgroup_of(self, other: api.QuotientSubgroup) -> bool:
        if not isinstance(other, QuotientSubgroup):
            raise TypeError("expected a toy QuotientSubgroup")
        if other._parent != self._parent:
            raise ParentMismatchError("subgroups of different parents")
        return self._elements <= other._elements

    def _local_centre(self, p: int) -> tuple[tree.Vertex, tree.Vertex]:
        """The centre of Fix(U_p) for a prime p dividing NM (maths: sec:subgroup-classes)."""
        parent = self._parent
        n, m = parent.N, parent.M
        k = arith.valuation(m, p) if m % p == 0 else 0
        sources = [tree.ORIGIN, tree.standard_neighbour()] if n % p == 0 else [tree.ORIGIN]
        candidates = tree.ball(p, sources, k)
        matrices = [parent._local_matrix(g, p) for g in self._gens]  # pyright: ignore[reportPrivateUsage]
        fixed = {v for v in candidates if all(tree.fixes(p, g, v) for g in matrices)}
        if not fixed:
            # No fixed vertex: U fixes c_N, so Fix(U_p) is the midpoint of the standard edge.
            other = tree.standard_neighbour()
            return (min(tree.ORIGIN, other), max(tree.ORIGIN, other))
        return tree.centre(p, fixed)

    def centre(self) -> tuple[tuple[int, tuple[int, int, int], tuple[int, int, int]], ...]:
        primes = sorted(arith.factor(self._parent.N * self._parent.M))
        return tuple((p, *self._local_centre(p)) for p in primes)

    def helling_level(self) -> int:
        level = 1
        for p, v, w in self.centre():
            if v != w:
                level *= p
        return level

    def is_centred(self) -> bool:
        n = self._parent.N
        edge = (min(tree.ORIGIN, tree.standard_neighbour()), max(tree.ORIGIN, tree.standard_neighbour()))
        for p, v, w in self.centre():
            expected = edge if n % p == 0 else (tree.ORIGIN, tree.ORIGIN)
            if (v, w) != expected:
                return False
        return True

    def principal_level(self) -> int:
        parent = self._parent
        big = parent.M
        for m in sorted(d for d in range(1, big + 1) if big % d == 0):
            kernel = parent._kernel_elements(m)  # pyright: ignore[reportPrivateUsage]
            if all(x in self._elements for x in kernel):
                return m
        raise AssertionError("the kernel modulo M is trivial")

    @override
    def __contains__(self, x: object) -> bool:
        return isinstance(x, QuotientElement) and x in self._elements

    @override
    def __eq__(self, other: object) -> bool:
        if not isinstance(other, QuotientSubgroup):
            return NotImplemented
        return self._parent == other._parent and self._elements == other._elements

    @override
    def __hash__(self) -> int:
        return hash((self._parent, self._gens))

    @override
    def __repr__(self) -> str:
        return f"subgroup of order {self.order()} of {self._parent!r}"

    def to_json(self) -> str:
        return _json.dumps(
            {
                "parent": self._parent._json_value(),  # pyright: ignore[reportPrivateUsage]
                "gens": [_json.encode_element(g.e, g.u) for g in self._gens],
            }
        )


class _Table:
    """The group as its multiplication table: element i is the i-th element in canonical order."""

    def __init__(self, parent: _QuotientGroup) -> None:
        self.elements = parent.elements()
        position = {x: i for i, x in enumerate(self.elements)}
        self.mul = [[position[x * y] for y in self.elements] for x in self.elements]
        self.inv = [position[x.inverse()] for x in self.elements]
        self.identity = position[parent.identity()]

    def closure(self, gens: Sequence[int], cap: int | None = None) -> frozenset[int] | None:
        """The subgroup generated by ``gens``, by breadth first search from the identity.

        Returns None as soon as it has more than ``cap`` elements.
        """
        seen = {self.identity}
        queue = [self.identity]
        while queue:
            x = queue.pop()
            for g in gens:
                y = self.mul[x][g]
                if y not in seen:
                    seen.add(y)
                    if cap is not None and len(seen) > cap:
                        return None
                    queue.append(y)
        return frozenset(seen)

    def subgroup(self, gens: Sequence[int]) -> frozenset[int]:
        """The subgroup generated by ``gens``."""
        result = self.closure(gens)
        assert result is not None
        return result

    def canonical_generators(self, elements: frozenset[int]) -> tuple[int, ...]:
        """def:canonical-generators; the canonical order is the order of the indices."""
        kept: list[int] = []
        span = frozenset({self.identity})
        for x in sorted(elements):
            if x not in span:
                kept.append(x)
                span = self.subgroup(kept)
        return tuple(kept)


def _search(table: _Table, gens: Sequence[int], max_index: int) -> list[tuple[frozenset[int], list[int]]]:
    """All subgroups of index <= max_index with their coset representatives (alg:coset-tables)."""
    order = len(table.elements)
    found: list[tuple[frozenset[int], list[int]]] = []

    def consistent(reps: list[int], h: frozenset[int]) -> bool:
        """The cosets r_i H are distinct."""
        return all(
            table.mul[table.inv[reps[i]]][reps[k]] not in h
            for i in range(len(reps))
            for k in range(i + 1, len(reps))
        )

    def extend(
        reps: list[int], defined: set[tuple[int, int]], schreier: list[int], h: frozenset[int]
    ) -> None:
        undefined = next(
            ((i, j) for i in range(len(reps)) for j in range(len(gens)) if (i, j) not in defined), None
        )
        if undefined is None:
            if len(reps) * len(h) == order:
                found.append((h, list(reps)))
            return
        i, j = undefined
        image = table.mul[gens[j]][reps[i]]  # s_j r_i
        elements = [table.mul[table.inv[reps[k]]][image] for k in range(len(reps))]  # r_k^{-1} s_j r_i
        if any(element in h for element in elements):
            # s_j r_i lies in a known coset r_k H: the entry is forced (any other choice, or a new
            # point, would put s_j r_i into two cosets).
            extend(reps, defined | {(i, j)}, schreier, h)
            return
        for element in elements:
            new_schreier = [*schreier, element]
            # n distinct cosets force |H| <= |G|/n: stop the closure early when it gets larger.
            new_h = table.closure(new_schreier, cap=order // len(reps))
            if new_h is not None and consistent(reps, new_h):
                extend(reps, defined | {(i, j)}, new_schreier, new_h)
        if len(reps) < max_index:
            new_reps = [*reps, image]
            if consistent(new_reps, h):
                extend(new_reps, defined | {(i, j)}, schreier, h)

    extend([table.identity], set(), [], frozenset({table.identity}))
    return found


def _subgroup_classes(  # pyright: ignore[reportUnusedFunction]  (used by quotient.py)
    parent: _QuotientGroup, max_index: int
) -> tuple[api.QuotientSubgroup, ...]:
    """Canonical representatives of the classes of subgroups of index <= max_index (alg:subgroup-classes)."""
    max_index = operator.index(max_index)
    if max_index < 1:
        raise InvalidParameterError("the index bound must be at least 1")
    table = _Table(parent)
    gens = table.canonical_generators(frozenset(range(len(table.elements))))
    classes: dict[tuple[int, ...], tuple[int, frozenset[int]]] = {}
    seen: set[frozenset[int]] = set()  # subgroups whose class has been handled
    for h, reps in _search(table, gens, max_index):
        if h in seen:
            continue
        # The conjugates of H are the point stabilisers r H r^{-1}; keep the least one.
        conjugates = {frozenset(table.mul[table.mul[r][x]][table.inv[r]] for x in h) for r in reps}
        seen |= conjugates
        key, best = min((table.canonical_generators(c), c) for c in conjugates)
        classes[key] = (len(reps), best)
    ordered = sorted(classes.items(), key=lambda item: (item[1][0], item[0]))
    return tuple(
        QuotientSubgroup(parent, [], frozenset(table.elements[i] for i in members))
        for _, (_, members) in ordered
    )


def subgroup_from_json(text: str) -> api.QuotientSubgroup:
    """See :func:`arithkit_api.modular.subgroup.subgroup_from_json`."""
    parent_value, gen_values = _json.decode_subgroup(_json.loads(text))
    parent = _quotient_from_value(parent_value)
    gens = [parent.element_from_json(_json.dumps(v)) for v in gen_values]
    return parent.subgroup(gens)
