"""Toy implementation of :mod:`arithkit_api.modular.subgroup`."""

from __future__ import annotations

from collections.abc import Sequence
from typing import override

from arithkit_api import _json
from arithkit_api.errors import ParentMismatchError
from arithkit_api.modular import quotient as api_quotient
from arithkit_api.modular import subgroup as api
from arithkit_toy.modular.quotient import (
    GL2ASubQuotient,
    GL2QSubQuotient,
    QuotientElement,
    _quotient_from_value,  # pyright: ignore[reportPrivateUsage]
    _QuotientGroup,  # pyright: ignore[reportPrivateUsage]
)


def _sort_key(x: QuotientElement) -> tuple[int, tuple[int, int, int, int]]:
    """The canonical order: lexicographic on (e, a, b, c, d)."""
    return (x.e, x.u)


def _closure(identity: QuotientElement, gens: Sequence[QuotientElement]) -> frozenset[QuotientElement]:
    """The subgroup generated by gens, by breadth first search from the identity.

    In a finite group the monoid generated by gens is already a group.
    """
    seen = {identity}
    queue = [identity]
    while queue:
        x = queue.pop()
        for g in gens:
            y = x * g
            if y not in seen:
                seen.add(y)
                queue.append(y)
    return frozenset(seen)


class QuotientSubgroup(api.QuotientSubgroup):
    """Toy implementation of :class:`arithkit_api.modular.subgroup.QuotientSubgroup`."""

    def __init__(self, parent: _QuotientGroup, gens: Sequence[QuotientElement]) -> None:
        self._parent = parent
        identity = parent.identity()
        self._elements = _closure(identity, gens)
        # Canonical generators: scan in canonical order, keep what is not yet generated.
        kept: list[QuotientElement] = []
        span = frozenset({identity})
        for x in sorted(self._elements, key=_sort_key):
            if x not in span:
                kept.append(x)
                span = _closure(identity, kept)
        self._gens = tuple(kept)

    def parent(self) -> api_quotient.GL2ASubQuotient | api_quotient.GL2QSubQuotient:
        p = self._parent
        assert isinstance(p, GL2ASubQuotient | GL2QSubQuotient)
        return p

    def order(self) -> int:
        return len(self._elements)

    def index(self) -> int:
        return self._parent.order() // self.order()

    def elements(self) -> tuple[api_quotient.QuotientElement, ...]:
        return tuple(sorted(self._elements, key=_sort_key))

    def gens(self) -> tuple[api_quotient.QuotientElement, ...]:
        return self._gens

    def al_image(self) -> tuple[int, ...]:
        return tuple(sorted({x.e for x in self._elements}))

    def is_subgroup_of(self, other: api.QuotientSubgroup) -> bool:
        if not isinstance(other, QuotientSubgroup):
            raise TypeError("expected a toy QuotientSubgroup")
        if other._parent != self._parent:
            raise ParentMismatchError("subgroups of different parents")
        return self._elements <= other._elements

    @override
    def __contains__(self, x: object) -> bool:
        return isinstance(x, QuotientElement) and x in self._elements

    @override
    def __eq__(self, other: object) -> bool:
        if not isinstance(other, QuotientSubgroup):
            return NotImplemented
        return self._parent == other._parent and self._elements == other._elements

    @override
    def __hash__(self) -> int:
        return hash((self._parent, self._gens))

    @override
    def __repr__(self) -> str:
        return f"subgroup of order {self.order()} of {self._parent!r}"

    def to_json(self) -> str:
        return _json.dumps(
            {
                "parent": self._parent._json_value(),  # pyright: ignore[reportPrivateUsage]
                "gens": [_json.encode_element(g.e, g.u) for g in self._gens],
            }
        )


def subgroup_from_json(text: str) -> api.QuotientSubgroup:
    """See :func:`arithkit_api.modular.subgroup.subgroup_from_json`."""
    parent_value, gen_values = _json.decode_subgroup(_json.loads(text))
    parent = _quotient_from_value(parent_value)
    gens = [parent.element_from_json(_json.dumps(v)) for v in gen_values]
    return parent.subgroup(gens)
