r"""The finite quotients $\Gamma_0(N)^*/\Gamma(N;M)$ (fine version).

Let $N, M \geq 1$ with $N$ squarefree and $N, M < 2^{63}$. Two finite groups
are implemented (sec:quotients, def:finite-quotients):

* the adelic quotient $\widehat{Q}_{N,M} = U_N/\widehat{\Gamma}(N;M)$, where
  $U_N = \widehat{\Gamma}_0(N)^*$ is the Atkin--Lehner group inside
  $\mathcal{G}^+ = \mathrm{GL}_2(\mathbb{A}_{\mathbb{Q},f})/\mathbb{Q}_{>0}$
  (:class:`GL2ASubQuotient`);
* the lifted (classical, fine) quotient
  $\widetilde{Q}_{N,M} = \widetilde{\Gamma}_0(N)^*/\widetilde{\Gamma}(N;M)$, in
  which $-1$ is a nontrivial element (:class:`GL2QSubQuotient`).

The projective quotient $Q_{N,M}$ and the coarse group are not implemented.

**Encoding** (prop:eichler-model, prop:al-encoding). An element is a pair
$(e, u)$:

* $e$ is a positive divisor of $N$, its *type*; the types form the group
  $T_N$ with product $e * e' = ee'/\gcd(e,e')^2$;
* $u = (a, b, c, d)$ with $a, b, c, d \in [0, M)$ stands for the class of
  $\begin{pmatrix} a & b \\ Nc & d \end{pmatrix}$ in $R_0(N)/MR_0(N)$, whose
  determinant $ad - Nbc$ is a unit modulo $M$ (adelic), respectively is
  $1$ modulo $M$ (lifted).

The pair stands for $u W_e$, with the fixed Atkin--Lehner matrices
$W_1 = 1$ and, for $e > 1$,
$W_e = \begin{pmatrix} e & y \\ N & ew \end{pmatrix}$ where $w$ is the least
positive integer with $ew \equiv 1 \bmod N/e$ and $y = (ew - 1)/(N/e)$
(proof of lem:global-al). The product is
$(e,u)(e',u') = (e * e',\ u\,\phi_e(u')\,\kappa(e,e'))$ with
$\phi_e(x) = W_e x W_e^{-1}$ and
$\kappa(e,e') = \gcd(e,e')^{-1} W_e W_{e'} W_{e*e'}^{-1}$.

The lifted quotient is the subgroup $\det u = 1$ of the adelic one, but the
two are different parents: their elements never compare equal, and
:meth:`GL2QSubQuotient.to_adelic` / :meth:`GL2ASubQuotient.to_lifted` convert.

**Canonical order** of elements: lexicographic on $(e, a, b, c, d)$.

**Printing**: an element prints as ``(e, (a, b, c, d))`` without its parent (print
the parent separately); a parent prints as ``GL2ASubQuotient(N, M)`` or
``GL2QSubQuotient(N, M)``. Both implementations print identically.

**JSON**: a parent is ``{"M":M,"N":N,"type":"GL2ASubQuotient","v":1}`` (or
``"GL2QSubQuotient"``); an element is ``[e,[a,b,c,d]]`` relative to its parent.
"""

from __future__ import annotations

from collections.abc import Iterable
from typing import TYPE_CHECKING, Protocol, Self

if TYPE_CHECKING:
    from arithkit_api.modular.subgroup import QuotientSubgroup


class _QuotientGroup(Protocol):
    """Methods shared by :class:`GL2ASubQuotient` and :class:`GL2QSubQuotient`."""

    @property
    def N(self) -> int:  # noqa: N802
        """The squarefree level $N$."""
        ...

    @property
    def M(self) -> int:  # noqa: N802
        """The level $M$ of the principal congruence subgroup $\\Gamma(N;M)$."""
        ...

    def __call__(self, e: int, u: tuple[int, int, int, int]) -> QuotientElement:
        """The element $(e, u)$.

        ``u`` must be a tuple of four integers; they are reduced modulo $M$.

        Raises :class:`~arithkit_api.errors.NotInGroupError` if $e$ is not a
        positive divisor of $N$ or if $\\det u$ is not a unit (adelic) or not
        $1$ (lifted) modulo $M$, and :class:`TypeError` if the arguments are
        not integers / a tuple of four integers.
        """
        ...

    def identity(self) -> QuotientElement:
        """The identity element $(1, (1, 0, 0, 1))$."""
        ...

    def al_element(self, e: int) -> QuotientElement:
        """The image of the fixed Atkin--Lehner matrix $W_e$, i.e. $(e, (1, 0, 0, 1))$.

        Raises :class:`~arithkit_api.errors.NotInGroupError` if $e$ is not a
        positive divisor of $N$.
        """
        ...

    def type_group(self) -> tuple[int, ...]:
        """The positive divisors of $N$ in increasing order, i.e. the elements of $T_N$."""
        ...

    def order(self) -> int:
        """The order of the group.

        $|\\widehat{Q}_{N,M}| = 2^{\\omega(N)} |(R_0(N)/MR_0(N))^\\times|$ and
        $|\\widetilde{Q}_{N,M}| = |\\widehat{Q}_{N,M}|/\\varphi(M)$.
        """
        ...

    def elements(self) -> tuple[QuotientElement, ...]:
        """All elements, in canonical order."""
        ...

    def subgroup(self, gens: Iterable[QuotientElement]) -> QuotientSubgroup:
        """The subgroup generated by ``gens`` (the trivial subgroup if ``gens`` is empty).

        Raises :class:`~arithkit_api.errors.ParentMismatchError` if a generator
        has a different parent.
        """
        ...

    def element_from_json(self, text: str) -> QuotientElement:
        """The element with canonical JSON text ``text`` (see :meth:`QuotientElement.to_json`).

        Raises :class:`~arithkit_api.errors.JsonFormatError` for malformed or
        non-canonical text and :class:`~arithkit_api.errors.NotInGroupError` if
        the determinant condition fails.
        """
        ...

    def to_json(self) -> str:
        """Canonical JSON text of the parent."""
        ...

    def __eq__(self, other: object) -> bool:
        """Parents are equal iff they have the same kind (adelic/lifted), $N$ and $M$."""
        ...

    def __hash__(self) -> int: ...


class GL2ASubQuotient(_QuotientGroup, Protocol):
    """The adelic quotient $\\widehat{Q}_{N,M} = U_N/\\widehat{\\Gamma}(N;M)$.

    Constructed as ``GL2ASubQuotient(N, M)``; raises
    :class:`~arithkit_api.errors.InvalidParameterError` unless
    $1 \\leq N, M < 2^{63}$ and $N$ is squarefree.
    """

    def to_lifted(self, x: QuotientElement) -> QuotientElement:
        """The element $x$ of $\\widehat{Q}_{N,M}$ as an element of $\\widetilde{Q}_{N,M}$.

        Raises :class:`~arithkit_api.errors.NotInGroupError` if $\\det u \\neq 1$
        and :class:`~arithkit_api.errors.ParentMismatchError` if $x$ has another
        parent.
        """
        ...


class GL2QSubQuotient(_QuotientGroup, Protocol):
    """The lifted quotient $\\widetilde{Q}_{N,M} = \\widetilde{\\Gamma}_0(N)^*/\\widetilde{\\Gamma}(N;M)$.

    Constructed as ``GL2QSubQuotient(N, M)``; raises
    :class:`~arithkit_api.errors.InvalidParameterError` unless
    $1 \\leq N, M < 2^{63}$ and $N$ is squarefree.
    """

    def from_matrix(self, g: tuple[tuple[int, int], tuple[int, int]]) -> QuotientElement:
        """The image of the integral matrix ``g`` (taken modulo $\\mathbb{Q}_{>0}$).

        ``g = ((g11, g12), (g21, g22))`` must have positive determinant and
        represent an element of $\\widetilde{\\Gamma}_0(N)^*$, i.e.
        $g = q \\gamma W_e$ with $q \\in \\mathbb{Q}_{>0}$ and
        $\\gamma \\in \\Gamma_0(N)$ of determinant 1 (lem:global-al); otherwise
        :class:`~arithkit_api.errors.NotInGroupError` is raised.
        """
        ...

    def to_adelic(self, x: QuotientElement) -> QuotientElement:
        """The element $x$ of $\\widetilde{Q}_{N,M}$ as an element of $\\widehat{Q}_{N,M}$.

        Raises :class:`~arithkit_api.errors.ParentMismatchError` if $x$ has
        another parent.
        """
        ...


class QuotientElement(Protocol):
    """An element $(e, u)$ of an :class:`GL2ASubQuotient` or a :class:`GL2QSubQuotient`.

    Products and comparisons with elements of another parent raise
    :class:`~arithkit_api.errors.ParentMismatchError` (``==`` returns False).
    """

    def parent(self) -> GL2ASubQuotient | GL2QSubQuotient:
        """The group containing this element."""
        ...

    def coordinates(self) -> tuple[int, tuple[int, int, int, int]]:
        """The canonical encoding $(e, (a, b, c, d))$ with $0 \\leq a, b, c, d < M$."""
        ...

    def type(self) -> int:
        """The type $e$, a positive divisor of $N$ (def:type)."""
        ...

    def det(self) -> int:
        """$\\det u = ad - Nbc$ reduced to $[0, M)$; always $1 \\bmod M$ in the lifted quotient."""
        ...

    def order(self) -> int:
        """The order of the element."""
        ...

    def inverse(self) -> Self:
        """The inverse element."""
        ...

    def __mul__(self, other: Self) -> Self:
        """The product (prop:al-encoding)."""
        ...

    def __pow__(self, k: int) -> Self:
        """The $k$-th power; negative $k$ gives powers of the inverse."""
        ...

    def __eq__(self, other: object) -> bool:
        """Equal iff the parents are equal and the encodings agree."""
        ...

    def __hash__(self) -> int: ...

    def to_json(self) -> str:
        """Canonical JSON text ``[e,[a,b,c,d]]`` relative to the parent."""
        ...

    def to_json_full(self) -> str:
        """Canonical JSON text ``{"element":[e,[a,b,c,d]],"parent":{...}}``."""
        ...


def quotient_from_json(text: str) -> GL2ASubQuotient | GL2QSubQuotient:  # pyright: ignore[reportReturnType]
    """The parent with canonical JSON text ``text`` (see :meth:`GL2ASubQuotient.to_json`)."""
    ...
