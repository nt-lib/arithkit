r"""Subgroups of the finite quotients, given by generators.

A subgroup $H$ of $\widehat{Q}_{N,M}$ (or $\widetilde{Q}_{N,M}$) is stored by
its set of elements.

**Canonical generators**: scan the elements of $H$ in canonical order and keep
each element that does not lie in the subgroup generated by the elements kept
so far. The result depends only on $H$.

**JSON**: ``{"gens":[...],"parent":{...}}`` with the canonical generators,
each encoded relative to the parent.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Protocol

if TYPE_CHECKING:
    from arithkit_api.modular.quotient import AdelicQuotient, LiftedQuotient, QuotientElement


class QuotientSubgroup(Protocol):
    """A subgroup of an :class:`~arithkit_api.modular.quotient.AdelicQuotient` or
    :class:`~arithkit_api.modular.quotient.LiftedQuotient`."""

    def parent(self) -> AdelicQuotient | LiftedQuotient:
        """The ambient group."""
        ...

    def order(self) -> int:
        """The number of elements."""
        ...

    def index(self) -> int:
        """The index in the parent."""
        ...

    def elements(self) -> tuple[QuotientElement, ...]:
        """All elements, in canonical order."""
        ...

    def gens(self) -> tuple[QuotientElement, ...]:
        """The canonical generators, in canonical order."""
        ...

    def al_image(self) -> tuple[int, ...]:
        """The types occurring in the subgroup, in increasing order (def:al-image)."""
        ...

    def is_subgroup_of(self, other: QuotientSubgroup) -> bool:
        """Whether this subgroup is contained in ``other``.

        Raises :class:`~arithkit_api.errors.ParentMismatchError` if the parents
        differ.
        """
        ...

    def __contains__(self, x: object) -> bool:
        """Whether ``x`` is an element of this subgroup (False for anything else)."""
        ...

    def __eq__(self, other: object) -> bool:
        """Equal iff the parents are equal and the element sets agree."""
        ...

    def __hash__(self) -> int: ...

    def to_json(self) -> str:
        """Canonical JSON text ``{"gens":[...],"parent":{...}}``."""
        ...


def subgroup_from_json(text: str) -> QuotientSubgroup:  # pyright: ignore[reportReturnType]
    """The subgroup with JSON text ``text``.

    The generators need not be the canonical ones, but each must be canonically
    encoded.
    """
    ...
