r"""Subgroups of the finite quotients, given by generators.

A subgroup $H$ of $\widehat{Q}_{N,M}$ (or $\widetilde{Q}_{N,M}$) is stored by
its set of elements.

**Canonical generators**: scan the elements of $H$ in canonical order and keep
each element that does not lie in the subgroup generated by the elements kept
so far. The result depends only on $H$.

**JSON**: ``{"gens":[...],"parent":{...}}`` with the canonical generators,
each encoded relative to the parent.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Protocol

if TYPE_CHECKING:
    from arithkit_api.modular.quotient import GL2ASubQuotient, GL2QSubQuotient, QuotientElement


class QuotientSubgroup(Protocol):
    """A subgroup of an :class:`~arithkit_api.modular.quotient.GL2ASubQuotient` or
    :class:`~arithkit_api.modular.quotient.GL2QSubQuotient`."""

    def parent(self) -> GL2ASubQuotient | GL2QSubQuotient:
        """The ambient group."""
        ...

    def order(self) -> int:
        """The number of elements."""
        ...

    def index(self) -> int:
        """The index in the parent."""
        ...

    def elements(self) -> tuple[QuotientElement, ...]:
        """All elements, in canonical order."""
        ...

    def gens(self) -> tuple[QuotientElement, ...]:
        """The canonical generators, in canonical order."""
        ...

    def al_image(self) -> tuple[int, ...]:
        """The types occurring in the subgroup, in increasing order (def:al-image)."""
        ...

    def is_subgroup_of(self, other: QuotientSubgroup) -> bool:
        """Whether this subgroup is contained in ``other``.

        Raises :class:`~arithkit_api.errors.ParentMismatchError` if the parents
        differ.
        """
        ...

    def centre(self) -> tuple[tuple[int, tuple[int, int, int], tuple[int, int, int]], ...]:
        r"""The centre of the corresponding compact open subgroup $U$ (def:helling-level).

        One entry ``(p, v, w)`` for every prime $p$ dividing $NM$, in increasing order (at the
        other primes the centre is the base vertex). ``v`` and ``w`` are vertices in the
        coordinates ``(m, r, s)`` of def:vertex-coordinates, meaning the class of
        $\begin{pmatrix} p^m & r/p^s \\ 0 & 1 \end{pmatrix}$; ``v == w`` if the centre is a vertex,
        otherwise the centre is the midpoint of the edge from ``v`` to ``w`` (``v < w``).
        In the lifted case $U$ is the closure of the preimage (lem:classical-fix).
        """
        ...

    def helling_level(self) -> int:
        """The Helling level: the product of the primes at which the centre is an edge midpoint."""
        ...

    def is_centred(self) -> bool:
        """Whether the centre is the standard point $c_N$ (def:centred-subgroup)."""
        ...

    def principal_level(self) -> int:
        r"""The least $m \mid M$ such that the subgroup contains the kernel of the reduction to
        level $m$ (def:principal-level); for centred subgroups the centred level quotient."""
        ...

    def __contains__(self, x: object) -> bool:
        """Whether ``x`` is an element of this subgroup (False for anything else)."""
        ...

    def __eq__(self, other: object) -> bool:
        """Equal iff the parents are equal and the element sets agree."""
        ...

    def __hash__(self) -> int: ...

    def to_json(self) -> str:
        """Canonical JSON text ``{"gens":[...],"parent":{...}}``."""
        ...


